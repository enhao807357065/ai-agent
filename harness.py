"""
模型负责“提出下一步建议”，Harness 负责“把建议变成受约束、可验证、可恢复的任务执行”。
一个agent并不是llm + tools，而是更接近llm + harness + tools + execution environment
单个模块正确，并不意味着任务整体正确：
模型正确选择了run_test
- 但任务仍可能失败：测试在错误的目录运行，验证不了目标代码
工具正确写入了文件
- 但任务仍可能失败：写入不在计划允许范围，或未留下可审计证据
进程退出码为0
- 但任务仍可能失败：agent可能根本没完成用户交付要求
测试显示通过
- 但任务仍可能失败：测试时旧版本代码执行的，修改后没有重新验证
因此，harness的目标不是“让模型更聪明”，而是建立一个可靠的任务操作系统

一、划清组件边界
harness不是单个模块，而是一组协作机制，典型层次如下：
┌──────────────────────────────────────────┐
│ Agent Runtime / Task Runtime              │
│ 启动、等待、取消、恢复、预算、收尾          │
│                                          │
│  ┌────────────────────────────────────┐  │
│  │ Agent Loop                          │  │
│  │ 模型 ↔ 工具 的多轮决策与交互          │  │
│  │                                    │  │
│  │  ┌──────────────────────────────┐  │  │
│  │  │ Tool Runtime                 │  │  │
│  │  │ 校验、授权、执行、超时、审计    │  │  │
│  │  └──────────────┬───────────────┘  │  │
│  └─────────────────┼──────────────────┘  │
│                    │                     │
│       State / Checkpoint / Evidence      │
└────────────────────┼─────────────────────┘
                     │
      ┌──────────────▼───────────────┐
      │ Tool + Sandbox / Environment │
      │ 文件、进程、网络、数据库等      │
      └──────────────────────────────┘

六大核心模块：
1. Tool：回答的是"我具体能做什么"，不应该负责决定任务是否完成、是否继续下一轮
2. Tool Runtime：回答的是"这个调用是否合法、是否允许、怎样执行与记录"，不应该让模型自由控制文件系统或权限
3. Loop：回答的是"下一轮要问模型什么，是否继续交互？"，不应该负责直接绕过runtime执行工具
4. State：回答的是"当前已知事实、计划、证据与未完成项是什么"，不应该负责把模型自然语言当作可信事实
5. Sandbox：回答的是"批准的动作实际最多能碰到哪里"，不应该负责代替业务授权与审批逻辑
6. Agent Runtime：回答的是"任务如何启动、暂停、取消、恢复、终止"，不应该负责代替Tool Runtime进行参数校验

Tool Runtime 是单次受控动作的执行入口。
Agent Runtime 是整体任务的生命周期管理。
"""

"""
一次工具调用，到底发生了什么
model → loop → runtime → tool/sandbox → result → loop
流程如图img.png

tool_call JSON不是可信指令，而是不可信输入
即便模型说tool=xxx arguments=xxx，runtime也不能因为模型说要改就执行，它必须检查tool runtime的一系列校验规则（路径、权限、审批等检查），只有全部通过才调用真正的tool handler

Tool 不应该决定"下一步"
tool的职责应该尽量窄：tool可以返回这个工具调用的结果，但是不应该返回任务已完成、接下来做xxx
原因是tool只知道一个动作、loop才知道当前对话和模型推理、agent runtime才知道任务预算、取消状态、计划状态和完成契约
"""

"""
工具结果为什么要同时交给模型和程序？
一次tool result有两种消费者：
                    Tool Result
                   /           \
                  /             \
      给模型（认知）         给程序（治理）

**模型上下文**
• 目的: 让模型决定下一步
• 典型内容: 文件片段、测试摘要、受控错误信息

**程序状态**
• 目的: 更新可信事实与任务状态
• 典型内容: call ID、执行状态、证据、耗时、错误码、版本号

如模型的自然语言结论：我已经修复并验证了问题。
不能直接作为完成依据

真正可用于完成判断的应该是：
- 是否存在受控的代码修改 Evidence？
- 修改后是否存在针对当前版本的测试 Evidence？
- Plan 中所有 required steps 是否已完成？
- 是否生成了要求的交付物？
"""

"""
首轮context该给什么，不该给什么？
context的目标不是尽可能多，而是足够让模型开始做正确的第一步。
首轮只需要提供4类信息：
- 目标：说明需要改变什么行为，以及关键约束
- 入口：告诉模型从哪里开始，不等于限定它只能看这些文件
- 边界：这是harness和runtime要落实的约束，而不是单纯写给模型看的提示词
- 验收：把完成从模糊感觉编程可验证契约

为什么不要把整个仓库塞给context：
- 信息密度过低：模型难以识别真正的关键文件
- context成本高：轮次变贵、响应变慢
- 代码会过期：改动后早期上下文不再反映当前文件
- 证据来源不清：模型可能基于"旧快照"判断
- 安全边界模糊：不必要的暴露敏感配置或无关内容

更好的工作模式是：
初始 Context：目标 + 入口 + 边界 + 验收
        ↓
模型提出读取需求
        ↓
Runtime 执行 read_file/search
        ↓
结果按需进入上下文
        ↓
模型基于最新、最小、可追溯的信息继续
"""

"""
状态、证据与完成条件
State不等于聊天记录
聊天记录记录"模型和工具说过什么"，而任务状态应记录"系统目前确认为什么是真的"
一个最小的任务状态可以是：
RunState
├── runId
├── status: running / waiting_approval / paused / cancelled / completed / failed
├── plan
│   ├── steps
│   └── dependencies
├── evidence
│   ├── code changes
│   ├── test results
│   └── investigation notes
├── action ledger
│   ├── intent
│   ├── outcome
│   └── unknown outcome
├── budgets
│   ├── turns
│   ├── elapsed time
│   └── tool attempts
├── pending approval
├── stop reason
└── checkpoint metadata

Plan、Fact、Evidence 三者不要混

**Plan**
• 含义: 未来想做什么
• 示例: “先定位重复扣款路径，再修改，再测试”

**Fact**
• 含义: 系统确认发生了什么
• 示例: “src/payment/x.ts 已被 Runtime 成功写入”

**Evidence**
• 含义: 支撑某个完成判断的可追溯事实
• 示例: “修改后的代码版本上，test:payment 通过”
"""

"""
程序结束 ≠ 任务完成
任务完成必须是一个语义判断，而不是进程退出判断

模型自然输出 Final Answer
• 进程是否结束: 是
• 任务是否完成: 不一定

达到最大轮数
• 进程是否结束: 是
• 任务是否完成: 否，属于预算耗尽

用户取消
• 进程是否结束: 是
• 任务是否完成: 否，属于取消

测试失败后 Agent 停止
• 进程是否结束: 是
• 任务是否完成: 否，属于未解决失败

所有 Plan 步骤完成且验收 Evidence 齐全
• 进程是否结束: 是
• 任务是否完成: 是

需要审批但用户尚未决定
• 进程是否结束: 当前 Loop 停止
• 任务是否完成: 否，属于等待审批
"""

"""
异常处理的第一原则——先确认动作是否发生
**明确未执行**
• 示例: 参数校验失败、权限拒绝
• 正确处理: 修正参数/权限；不需要现场核对

**明确失败**
• 示例: 测试退出码为 1
• 正确处理: 分析失败原因，改变下一次行动

**明确成功**
• 示例: 写入成功但之后模型请求失败
• 正确处理: 保存成功事实，继续或恢复

**结果不明**
• 示例: 写文件时进程崩溃、网络超时
• 正确处理: 先核对现场，不能直接重试

"结果不明"为什么危险？
A. 文件没改
B. 文件完全改了
C. 文件写到一半，留下部分状态
如果直接重试，可能：
- 第二次替换找不到旧文本；
- 覆盖掉人工后续修改；
- 非幂等业务操作发生两次；
- 重复发邮件、重复扣款、重复创建资源。
因此要进入：
outcome_unknown
  ↓
现场核对（read_file / git diff / 查询业务状态）
  ↓
修正 State
  ↓
再决定继续、人工介入或终止


本地代码写入结果不明时
按可靠性从低到高：
1. 读取目标文件并检查预期内容
   - 原文本还在 → 大概率未改；
   - 新文本完整出现、原文本消失 → 大概率已改；
   - 两者都不符合 / 文件截断 → 可能部分写入，必须人工或更严格恢复处理。

2. 检查 Git 工作区
   git diff -- path/to/file
   git status --short
看目标文件相对任务开始前是否产生了变更。

3. 用文件内容摘要（digest）比对
   在写入前保存目标文件的 beforeDigest，恢复时重新计算：
      currentDigest == beforeDigest  → 很可能未写入
   currentDigest == expectedAfterDigest → 已完整写入
   其他 → 状态冲突/部分写入/外部修改

4. 更可靠的工程做法：原子写入
   写入临时文件 → fsync（可选）→ rename 覆盖目标文件

harness中的标准策略：
写前：记录 intent + beforeDigest + 预期 afterDigest
写后：记录 success + 实际 afterDigest

若中断发生在两者之间：
  标记 outcome_unknown
  → 重新读取文件、计算 currentDigest
  → 与 before/after 对比
  → 再决定已成功、未执行，还是冲突
"""
